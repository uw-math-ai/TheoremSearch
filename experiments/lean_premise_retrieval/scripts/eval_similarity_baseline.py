"""Raw-cosine retrieval baseline (the floor): for each held-out test target, use its own slogan
embedding as the query and measure recall@k of its gold premises, with forbidden masking
(target + transitive reverse-deps). No learned head — this is what an off-the-shelf embedding
gives you, and the bar the learned query head must beat.

Self-contained: reads only artifacts regenerated by build_formal_index.py + build_split.py.

    python scripts/eval_similarity_baseline.py
"""
import json
import pickle
import random
import statistics as st
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from src.formal_retriever import FormalRetriever

CACHE = Path(__file__).resolve().parent.parent / "cache"
KS = [5, 10, 20, 50, 100]
N_EVAL = 3000   # sampled test subset (stable estimate; full test ~37k is slow)
SEED = 42


def bucket(n):
    return "2" if n == 2 else "3" if n == 3 else "4-5" if n <= 5 else "6+"


def build_forbidden_fn(gold_edges):
    """forbidden(F) = {F} ∪ everything that transitively depends on F (reverse-dep closure)."""
    rev = defaultdict(set)
    for src, deps in gold_edges.items():
        for d in deps:
            rev[d].add(src)

    def forbidden(F):
        seen = {F}
        stack = [F]
        while stack:
            x = stack.pop()
            for up in rev.get(x, ()):
                if up not in seen:
                    seen.add(up)
                    stack.append(up)
        return seen
    return forbidden


def main():
    r = FormalRetriever(CACHE / "formal_emb.f16.npy", CACHE / "formal_ids.json")
    targets = pickle.load(open(CACHE / "targets_full.pkl", "rb"))
    split = json.loads((CACHE / "split.json").read_text())
    gold_edges = pickle.load(open(CACHE / "gold_edges.pkl", "rb"))
    forbidden = build_forbidden_fn(gold_edges)

    test = [t for t, s in split.items() if s == "test" and t in r.row_of]
    random.Random(SEED).shuffle(test)
    test = test[:N_EVAL]
    print(f"index: {len(r.ids):,} docs   test targets (sampled): {len(test):,}")

    rec = {k: [] for k in KS}
    rec_b = {}
    maxk = max(KS)
    n_eval = 0
    for tid in test:
        gold = {g for g in targets[tid]["gold"] if g in r.row_of}
        if len(gold) < 2:
            continue
        qvec = r.vec_for(tid)
        forb = forbidden(tid)
        hits = r.search_by_vec(qvec, maxk + len(forb), exclude_ids=forb)
        ranked = [sid for sid, _ in hits][:maxk]
        b = bucket(len(gold))
        rec_b.setdefault(b, {k: [] for k in KS})
        for k in KS:
            got = len(gold & set(ranked[:k])) / len(gold)
            rec[k].append(got)
            rec_b[b][k].append(got)
        n_eval += 1

    print(f"evaluated {n_eval} test targets (>= 2 gold deps in index)\n")
    print("=== raw cosine recall@k (forbidden masked) ===")
    for k in KS:
        print(f"  recall@{k:<3}: {st.mean(rec[k]):.3f}")
    print("\n=== by dep-count bucket ===")
    print("  bucket   n      " + "  ".join(f"R@{k}" for k in KS))
    for b in ["2", "3", "4-5", "6+"]:
        if b in rec_b:
            n = len(rec_b[b][KS[0]])
            cells = "  ".join(f"{st.mean(rec_b[b][k]):.2f}" for k in KS)
            print(f"  {b:<7} {n:<6} {cells}")


if __name__ == "__main__":
    main()
