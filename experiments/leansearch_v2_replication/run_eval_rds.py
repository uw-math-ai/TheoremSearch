"""MathlibQR evaluation against our retriever, via direct RDS access.

Replicates the deployed /graph/embedding pipeline with one targeted fix: the
source filter is pushed into the inner ANN CTE so HNSW can iterate against the
~4% Lean Repo slice without timing out. See handoff doc for rationale.

Inputs:
  - benchmark JSON at formalized_graph/docs/paper_writing/leansearch_v2_external/benchmark/MathlibQR.json
  - shared-171 fair-subset list at .../MathlibQR_shared171.json (key: shared_declarations)
  - .env at /mmfs1/gscratch/amath/simku22/TheoremSearch/.env (AWS_*, RDS_SECRET_ARN, NEBIUS_API_KEY)
  - RDS tunnel on localhost:5432 (open via bastion before running)

Outputs (written next to this script under data/):
  - per_query.jsonl   (one row per populated query cell)
  - summary.json      (overall + by_style + by_difficulty + by_kind, on full + fair-810 subsets,
                       plus a corpus-coverage diagnostic)

Usage:
  python3 run_eval_rds.py --pilot 1            # single query (lattice / Lattice)
  python3 run_eval_rds.py --pilot 30           # first 30 populated cells
  python3 run_eval_rds.py                      # full 946-cell run

All knobs match deployed-API constants verbatim (verified 2026-05-24 against
api/routes/graph.py at HEAD): _EMBED_MODEL='qwen3-8b', _SLOGAN_MODELS=['qwen3-235b'],
_QUERY_INSTRUCTION='Given a math search query, ...'.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import sys
import time
from pathlib import Path
from typing import Optional

import boto3
import psycopg2
from openai import OpenAI


REPO_ROOT = Path("/mmfs1/gscratch/amath/simku22/TheoremSearch")
BENCH_DIR = REPO_ROOT / "formalized_graph/docs/paper_writing/leansearch_v2_external/benchmark"
DATA_DIR = REPO_ROOT / "experiments/leansearch_v2_replication/data"

# ---- constants pulled from api/routes/graph.py (verified 2026-05-24) ----
EMBED_MODEL = "qwen3-8b"
SLOGAN_MODELS = ["qwen3-235b"]
QUERY_INSTRUCTION = "Given a math search query, retrieve theorems mathematically equivalent to the query.\n"
SOURCES = ["Lean Repo"]
# Restrict retrieval to the same Mathlib pin as the gold set (v427 ∪ v428) —
# apples-to-apples with LSv2's Mathlib v4.28.0-rc1 corpus. Without this,
# community-project and v429 slogans take top-10 slots without ever being
# counted as hits, deflating our reported recall/nDCG vs LSv2.
MATHLIB_EXTERNAL_IDS = ["Mathlib_v427", "Mathlib_v428"]
TOP_K = 10           # what we score
ANN_K = 200          # inner-CTE candidate pool
# pgvector HNSW knobs. Max ef_search is 1000 in this build; ef=500 hits the
# sweet spot empirically — ef=200 retrieves 200 rows in 0.18s (probably
# subsampling), ef=500 still 0.19s, ef=1000 jumps to 18s (planner switches
# strategy). 500 keeps relaxed_order iterative scan fast while giving the
# binary shortlist enough variety to recall Lean Repo candidates.
EF_SEARCH = 500
STMT_TIMEOUT_MS = 120_000

STYLES = ("q1a_lean", "q1b_latex", "q1c_natural", "q2_slogan", "q3_nickname", "q4_special_case")

# Source filter is pushed into the inner CTE via a session-temp table
# (lean_slogan_ids) built once at startup. Joining the temp table inside the
# ORDER BY lets pgvector iterate the HNSW index until LIMIT 200 rows match,
# instead of post-filtering 200 ANN candidates down to ~1 Lean Repo row.
# Outer SELECT does the full-precision cosine rerank + decl_name join.
EMBEDDING_SQL = """
WITH ann AS (
    SELECT e.slogan_id, e.embedding
    FROM embedding e
    JOIN lean_slogan_ids ls ON ls.slogan_id = e.slogan_id
    WHERE e.model_name = %(model)s
    ORDER BY
        binary_quantize(e.embedding)::bit(4096)
        <~>
        binary_quantize(%(q)s::vector(4096))::bit(4096)
    LIMIT %(ann_k)s
)
SELECT
    st.statement_id,
    p.paper_id,
    p.external_id          AS paper_external_id,
    fm.decl_name,
    st.kind,
    1.0 - (ann.embedding <=> %(q)s::vector(4096)) AS similarity
FROM ann
JOIN slogan s     ON s.slogan_id = ann.slogan_id
JOIN statement st ON st.statement_id = s.statement_id
JOIN paper p      ON p.paper_id = st.paper_id
LEFT JOIN formal_metadata fm ON fm.statement_id = st.statement_id
ORDER BY ann.embedding <=> %(q)s::vector(4096)
LIMIT %(top_k)s;
"""

# Built once per session. Holds slogan_ids of every Mathlib v427+v428 slogan
# that (a) was generated by the deployed slogan model and (b) wasn't marked
# insufficient_context. ~337K rows (330K v427 + 7K v428); build cost a few
# seconds warm; indexed on slogan_id. The table name still says
# "lean_slogan_ids" for code-locality with the inner-CTE join — the contents
# are Mathlib-restricted per MATHLIB_EXTERNAL_IDS.
TEMP_TABLE_SQL = """
CREATE TEMP TABLE IF NOT EXISTS lean_slogan_ids AS
SELECT s.slogan_id
FROM slogan s
JOIN statement st ON st.statement_id = s.statement_id
JOIN paper p      ON p.paper_id     = st.paper_id
WHERE s.model_name = ANY(%(slogan_models)s)
  AND NOT s.insufficient_context
  AND p.source = ANY(%(sources)s)
  AND p.external_id = ANY(%(mathlib_ids)s)
"""


def load_env() -> dict:
    env = {}
    with open(REPO_ROOT / ".env") as f:
        for line in f:
            if line.strip() and not line.startswith("#") and "=" in line:
                k, _, v = line.strip().partition("=")
                env[k] = v.strip("'\"")
    return env


def db_connect(env: dict) -> psycopg2.extensions.connection:
    sm = boto3.client(
        "secretsmanager",
        region_name=env.get("AWS_REGION", "us-west-2"),
        aws_access_key_id=env["AWS_ACCESS_KEY_ID"],
        aws_secret_access_key=env["AWS_SECRET_ACCESS_KEY"],
    )
    secret = json.loads(sm.get_secret_value(SecretId=env["RDS_SECRET_ARN"])["SecretString"])
    conn = psycopg2.connect(
        host="localhost", port=5432, dbname="v2",
        user=secret["username"], password=secret["password"],
        sslmode="require",
        options=f"-c statement_timeout={STMT_TIMEOUT_MS}",
    )
    with conn.cursor() as cur:
        # pgvector's HNSW GUCs are registered lazily — they only become
        # SHOW/SET-able after the extension is touched in this session.
        cur.execute("SELECT '[1]'::vector(1)")
        cur.fetchone()
        cur.execute("SET hnsw.iterative_scan = relaxed_order")
        cur.execute(f"SET hnsw.ef_search = {EF_SEARCH}")
    return conn


def build_lean_temp_table(conn) -> int:
    with conn.cursor() as cur:
        cur.execute(TEMP_TABLE_SQL, {
            "slogan_models": SLOGAN_MODELS,
            "sources": SOURCES,
            "mathlib_ids": MATHLIB_EXTERNAL_IDS,
        })
        cur.execute("CREATE INDEX IF NOT EXISTS lean_slogan_ids_pk ON lean_slogan_ids (slogan_id)")
        cur.execute("ANALYZE lean_slogan_ids")
        cur.execute("SELECT COUNT(*) FROM lean_slogan_ids")
        n = cur.fetchone()[0]
    conn.commit()
    return n


def resolve_provider_model(conn) -> str:
    with conn.cursor() as cur:
        cur.execute("SELECT model FROM embedding_model WHERE name = %s", (EMBED_MODEL,))
        row = cur.fetchone()
    if row is None:
        raise RuntimeError(f"embedding_model row missing for name={EMBED_MODEL!r}")
    return row[0]


def make_oai(env: dict) -> OpenAI:
    return OpenAI(base_url="https://api.studio.nebius.ai/v1/", api_key=env["NEBIUS_API_KEY"])


def embed_query(oai: OpenAI, provider_model: str, query: str) -> list[float]:
    resp = oai.embeddings.create(
        model=provider_model,
        input=QUERY_INSTRUCTION + query,
        encoding_format="float",
    )
    vec = resp.data[0].embedding
    norm = math.sqrt(sum(x * x for x in vec))
    return [x / norm for x in vec] if norm > 0 else vec


def vec_literal(vec: list[float]) -> str:
    # pgvector text literal: '[v1,v2,...]'
    return "[" + ",".join(f"{x:.7g}" for x in vec) + "]"


def retrieve_top10(conn, query_vec_literal: str) -> list[dict]:
    params = {
        "q": query_vec_literal,
        "model": EMBED_MODEL,
        "ann_k": ANN_K,
        "top_k": TOP_K,
    }
    with conn.cursor() as cur:
        cur.execute(EMBEDDING_SQL, params)
        rows = cur.fetchall()
    out = []
    for rank, (sid, pid, ext, decl, kind, sim) in enumerate(rows, start=1):
        out.append({
            "rank": rank,
            "statement_id": str(sid),
            "paper_id": str(pid),
            "paper_external_id": ext,
            "decl_name": decl,
            "kind": kind,
            "similarity": float(sim),
        })
    return out


def first_hit_rank(top10: list[dict], target_full_name: str, mathlib_paper_ids: set[str]) -> Optional[int]:
    for r in top10:
        if r["paper_id"] in mathlib_paper_ids and r["decl_name"] == target_full_name:
            return r["rank"]
    return None


def metric_pair(hit_rank: Optional[int]) -> tuple[float, float]:
    if hit_rank is None:
        return 0.0, 0.0
    # binary relevance, single gold doc, K=10, IDCG=1
    return 1.0, 1.0 / math.log2(hit_rank + 1)


def aggregate(rows: list[dict], filter_fn=lambda r: True) -> dict:
    sub = [r for r in rows if filter_fn(r)]
    if not sub:
        return {"n": 0, "recall@10": None, "ndcg@10": None}
    return {
        "n": len(sub),
        "recall@10": sum(r["recall@10"] for r in sub) / len(sub),
        "ndcg@10": sum(r["ndcg@10"] for r in sub) / len(sub),
    }


def build_summary(rows: list[dict], coverage: dict) -> dict:
    def by(field, fair_only=False):
        vals = sorted({r[field] for r in rows})
        return {v: aggregate(rows, lambda r, v=v: r[field] == v and (r["in_shared171"] if fair_only else True))
                for v in vals}

    return {
        "overall": {
            "full_946": aggregate(rows),
            "fair_810": aggregate(rows, lambda r: r["in_shared171"]),
        },
        "by_style": {
            "full_946": by("style"),
            "fair_810": by("style", fair_only=True),
        },
        "by_difficulty": {
            "full_946": by("difficulty"),
            "fair_810": by("difficulty", fair_only=True),
        },
        "by_kind": {
            "full_946": by("kind"),
            "fair_810": by("kind", fair_only=True),
        },
        "corpus_coverage": coverage,
        "config": {
            "embed_model": EMBED_MODEL,
            "slogan_models": SLOGAN_MODELS,
            "sources": SOURCES,
            "mathlib_external_ids": MATHLIB_EXTERNAL_IDS,
            "top_k": TOP_K,
            "ann_k": ANN_K,
            "ef_search": EF_SEARCH,
            "query_instruction": QUERY_INSTRUCTION,
        },
    }


def corpus_coverage(conn, full_names: list[str], paper_ids: set[str]) -> dict:
    """Count how many MathlibQR full_names exist in our v427/v428 formal_metadata."""
    with conn.cursor() as cur:
        cur.execute(
            """
            SELECT DISTINCT fm.decl_name
            FROM formal_metadata fm
            JOIN statement st ON st.statement_id = fm.statement_id
            WHERE st.paper_id = ANY(%s::uuid[])
              AND fm.decl_name = ANY(%s)
            """,
            (list(paper_ids), full_names),
        )
        present = {r[0] for r in cur.fetchall()}
    missing = sorted(set(full_names) - present)
    return {
        "n_decls_total": len(full_names),
        "n_decls_present": len(present),
        "n_decls_missing": len(missing),
        "missing_full_names": missing,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pilot", type=int, default=0,
                    help="If >0, run only the first N populated query cells.")
    ap.add_argument("--out-jsonl", default=None,
                    help="Override per-query JSONL output path (default: data/per_query.jsonl, "
                         "or data/per_query_pilot{N}.jsonl when --pilot > 0).")
    ap.add_argument("--out-summary", default=None,
                    help="Override summary JSON output path (default: data/summary.json, "
                         "or data/summary_pilot{N}.json when --pilot > 0).")
    ap.add_argument("--query", default=None,
                    help="Ad-hoc: run a single query string and print top-10. Skips benchmark.")
    args = ap.parse_args()

    DATA_DIR.mkdir(parents=True, exist_ok=True)

    env = load_env()
    conn = db_connect(env)
    oai = make_oai(env)
    provider_model = resolve_provider_model(conn)
    t0 = time.time()
    n_lean = build_lean_temp_table(conn)
    print(f"[init] provider_model={provider_model} ann_k={ANN_K} top_k={TOP_K} ef_search={EF_SEARCH}",
          file=sys.stderr, flush=True)
    print(f"[init] lean_slogan_ids: {n_lean} rows in {time.time()-t0:.1f}s",
          file=sys.stderr, flush=True)

    if args.query is not None:
        t0 = time.time()
        vec = embed_query(oai, provider_model, args.query)
        t_emb = time.time() - t0
        t0 = time.time()
        top10 = retrieve_top10(conn, vec_literal(vec))
        t_q = time.time() - t0
        print(f"[adhoc] query={args.query!r} embed={t_emb:.2f}s query={t_q:.2f}s")
        for r in top10:
            print(f"  rank={r['rank']:2d} sim={r['similarity']:.4f} "
                  f"{r['paper_external_id']:>14s} {r['kind']:>12s}  {r['decl_name']}")
        return

    rows = json.load(open(BENCH_DIR / "MathlibQR.json"))
    shared = json.load(open(BENCH_DIR / "MathlibQR_shared171.json"))
    shared171 = set(shared["shared_declarations"])

    # Resolve v427/v428 paper_ids fresh from DB rather than hard-coding.
    with conn.cursor() as cur:
        cur.execute(
            "SELECT paper_id FROM paper WHERE external_id IN ('Mathlib_v427','Mathlib_v428')"
        )
        mathlib_paper_ids = {str(r[0]) for r in cur.fetchall()}
    print(f"[init] mathlib paper_ids: {sorted(mathlib_paper_ids)}", file=sys.stderr, flush=True)

    # Build the flat (decl, style) cell list, preserving original decl order.
    cells = []
    for r in rows:
        for s in STYLES:
            q = (r.get(s) or "").strip()
            if not q:
                continue
            cells.append({
                "decl_id": r["id"],
                "full_name": r["full_name"],
                "file": r.get("file"),
                "difficulty": r.get("difficulty"),
                "kind": r.get("kind"),
                "style": s,
                "query": q,
                "in_shared171": r["full_name"] in shared171,
            })
    print(f"[init] populated query cells: {len(cells)}", file=sys.stderr, flush=True)

    coverage = corpus_coverage(conn, sorted({c["full_name"] for c in cells}), mathlib_paper_ids)
    print(f"[init] corpus coverage: {coverage['n_decls_present']}/{coverage['n_decls_total']} "
          f"({coverage['n_decls_missing']} missing)", file=sys.stderr, flush=True)

    if args.pilot:
        cells = cells[: args.pilot]
        print(f"[init] PILOT mode: limiting to {len(cells)} cells", file=sys.stderr, flush=True)

    suffix = f"_pilot{args.pilot}" if args.pilot else ""
    jsonl_path = Path(args.out_jsonl) if args.out_jsonl else DATA_DIR / f"per_query{suffix}.jsonl"
    summary_path = Path(args.out_summary) if args.out_summary else DATA_DIR / f"summary{suffix}.json"

    results = []
    t_run_start = time.time()
    with open(jsonl_path, "w", buffering=1) as fout:
        for i, c in enumerate(cells, start=1):
            t0 = time.time()
            try:
                vec = embed_query(oai, provider_model, c["query"])
                top10 = retrieve_top10(conn, vec_literal(vec))
                hit_rank = first_hit_rank(top10, c["full_name"], mathlib_paper_ids)
                recall, ndcg = metric_pair(hit_rank)
                row = {**c, "hit_rank": hit_rank, "recall@10": recall, "ndcg@10": ndcg, "top10": top10}
            except Exception as e:
                row = {**c, "hit_rank": None, "recall@10": 0.0, "ndcg@10": 0.0, "top10": [], "error": repr(e)}
                # Reset transaction state on error so subsequent queries succeed.
                conn.rollback()
            dt = time.time() - t0
            fout.write(json.dumps(row, ensure_ascii=False) + "\n")
            results.append(row)
            if i % 10 == 0 or i == len(cells):
                elapsed = time.time() - t_run_start
                rate = elapsed / i
                eta = rate * (len(cells) - i)
                hits = sum(1 for r in results if r["hit_rank"])
                print(f"[{i:4d}/{len(cells)}] {dt:.2f}s  hits={hits}  elapsed={elapsed:.0f}s  eta={eta:.0f}s",
                      file=sys.stderr, flush=True)

    summary = build_summary(results, coverage)
    with open(summary_path, "w") as fout:
        json.dump(summary, fout, indent=2, ensure_ascii=False)
    print(f"[done] per_query → {jsonl_path}", file=sys.stderr)
    print(f"[done] summary   → {summary_path}", file=sys.stderr)
    o = summary["overall"]
    print(f"[done] overall full_946: recall@10={o['full_946']['recall@10']:.4f} "
          f"ndcg@10={o['full_946']['ndcg@10']:.4f} (n={o['full_946']['n']})", file=sys.stderr)
    if o["fair_810"]["n"]:
        print(f"[done] overall fair_810: recall@10={o['fair_810']['recall@10']:.4f} "
              f"ndcg@10={o['fair_810']['ndcg@10']:.4f} (n={o['fair_810']['n']})", file=sys.stderr)


if __name__ == "__main__":
    main()
